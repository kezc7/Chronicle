let uiLanguage = 'en';

function t(key, vars) {
  const table = STRINGS[uiLanguage] || STRINGS.en;
  let text = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
    : Object.prototype.hasOwnProperty.call(STRINGS.en, key) ? STRINGS.en[key] : String(key);
  if (vars) text = text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
  return text;
}

function normalizeLanguage(setting) {
  return setting === 'auto' || LANGUAGES.includes(setting) ? setting : 'auto';
}

// "auto" (or anything unknown) follows the game; unsupported game languages use English.
function resolveLanguage(setting, gameLanguage) {
  if (LANGUAGES.includes(setting)) return setting;
  return GAME_LANGUAGES[String(gameLanguage || '').trim().toUpperCase()] || 'en';
}

// Elements carry data-i18n (text), data-i18n-placeholder, data-i18n-title or
// data-i18n-aria-label with the key to show.
function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attr of ['placeholder', 'title', 'aria-label']) {
    root.querySelectorAll('[data-i18n-' + attr + ']').forEach(el => {
      el.setAttribute(attr, t(el.getAttribute('data-i18n-' + attr)));
    });
  }
  if (document.documentElement) document.documentElement.lang = uiLanguage;
}
